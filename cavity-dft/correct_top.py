#!/usr/bin/env python

import shutil
import argparse as arg


def options():

    parser = arg.ArgumentParser(
                formatter_class=arg.ArgumentDefaultsHelpFormatter)

    #
    # Input Options
    #
    inp = parser.add_argument_group("Input Data")

    inp.add_argument('-i', '--itp', type=str, dest='ItpFile', required=True,
                     help='''Gromacs .itp file''')

    inp.add_argument('-r', '--res', type=str, dest='ResName', default="RET",
                     help='''Residue Name for the correction''')

    args = parser.parse_args()
    Opts = vars(args)

    return Opts


def correct_gromacs_itp(itpfile, resname="RET"):
    '''
    This function fixes the topology generated by pdb2gmx when using a
    Force Field fitted with Joyce: harmonic potentials on improper dihedrals
    (func = 2 in gromacs) cannot be automatically set from the .rtp in the FF,
    which only sets impropers to func = 4. So here we identify such improper
    dihedrals, based on the residue name, and replace them with a harmonic
    potential.

    Parameters
    ----------
    itpfile: str.
        Gromacs topology to process.
    resname: str.
        Three letter residue name to identify the residue to process in the
        provided itpfile.
    '''

    ret_atnums = []
    corrected_top = []
    with open(itpfile) as f:
        for line in f:
            if line.startswith(";"):
                corrected_top.append(line)
                continue

            elif resname in line:
                corrected_top.append(line)
                atnum = line.split()[0]
                ret_atnums.append(atnum)

            elif "dihedrals" in line:
                corrected_top.append(line)
                line = next(f)
                corrected_top.append(line)
                line = next(f)
                while len(line.strip()) != 0:
                    data = line.strip().split()
                    at1, at2, at3, at4, func = data[:5]
                    if at1 in ret_atnums and at2 in ret_atnums and at3 in ret_atnums and at4 in ret_atnums and func == "4":
                        data[4] = "2"
                        data = data[:-1]
                        fmt = " %-5s %-5s %-5s %-5s %4s %8s %10s\n"
                        newline = fmt % tuple(data)
                        corrected_top.append(newline)
                    else:
                        corrected_top.append(line)
                    line = next(f)

            else:
                corrected_top.append(line)

    write_file(corrected_top, itpfile)

    return


def write_file(lines, filename):

    shutil.move(filename, filename + ".old")
    with open(filename, "w") as f:
        for line in lines:
            f.write(line)

    return


if __name__ == '__main__':

    Opts = options()
    correct_gromacs_itp(Opts["ItpFile"], resname=Opts["ResName"])
