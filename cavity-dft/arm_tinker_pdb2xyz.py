def assign_tk_types(pdbfile):
    '''
    Function to assign Tinker atom names and atom types to a pdb.

    Parameters
    ----------
    pdbfile: str.
        Input pdb file name.

    Returns
    -------
    atinfos: list.
        List of tuples. Each element of the list corresponds to an atom in the
        input pdb file, to which a pair (atom_name, atom_type) are associated
        within a tuple.
    '''

    # read pdb with resid info only for protein
    resids = []
    resnames = []
    pdblines = []
    cys = []
    with open(pdbfile) as f:
        for line in f:

            line = line.rstrip()
            if line.startswith("ATOM"):

                ls = line.split()
                resids.append(ls[5])
                resnames.append(ls[3])

                # Distinguish between Cysteine (-SH) and Cystine (-S-S-)
                if ls[3] == "CYS" and ls[2] == "HG":
                    cys.append(ls[5])

            pdblines.append(line)

    # Identify where protein chains end
    resids_names = zip(resids, resnames)
    resids_names = [ x[0] for x in groupby(resids_names) ]
    resids = [ int(x[0]) for x in resids_names ]
    resnames = [ x[1] for x in resids_names ]

    diff = np.diff(resids)
    idxs = np.where(diff > 1)

    # Identify C-term and N-term residues
    C_idxs = [ resids[-1] ] + [ int(resids[i]) for i in idxs[0] ]
    N_idxs = [ resids[0] ] + [ int(resids[i + 1]) for i in idxs[0] ]

    # Seq file info
    chains = np.split(resnames, idxs[0] + 1)
    chains = [ x.tolist() for x in chains ]

    # Loop over lines and assign atom types according to the dict
    # Update the residue dict with the terminal residues dict if appropriate
    atinfos = []
    for line in pdblines:

            if line.startswith("ATOM"):
                ls = line.split()
                resid = int(ls[5])
                resname = ls[3]
                atname = ls[2]

                if resname == "CYS" and str(resid) in cys:
                    assignment_dict = gro2tk["CYS"].copy()
                elif resname == "CYS" and str(resid) not in cys:
                    assignment_dict = gro2tk["CYSS"].copy()
                else:
                    assignment_dict = gro2tk[resname].copy()

                if resid in N_idxs:
                    assignment_dict.update(nterm[resname])
                elif resid in C_idxs:
                    assignment_dict.update(cterm[resname])

                atinfo = assignment_dict[atname]
                atinfos.append(atinfo)

            if line.startswith("HETATM"):
                ls = line.split()
                resid = int(ls[5])
                resname = ls[3]
                atname = ls[2]

                assignment_dict = gro2tk[resname]
                atinfo = assignment_dict[atname]
                atinfos.append(atinfo)

    return atinfos, chains


def correct_txyz(txyzfile, atinfos, outxyz=None):
    '''
    Function to correct atom names and atom types in Tinker xyz file.

    Parameters
    ----------
    txyzfile: str.
        Input Tinker xyz file name.
    atinfos: list.
        List of tuples. Each element of the list corresponds to an atom in the
        input pdb file, to which a pair (atom_name, atom_type) are associated
        within a tuple.
    outxyz: str.
        Output Tinker xyz file name.
    '''

    ions = [ str(i + 1) for i, x in enumerate(atinfos) if x[0] in ["K+", "Cl-", "Na+"] ]
    newlines = []
    with open(txyzfile) as f:
        for i, line in enumerate(f):

            line = line.rstrip()
            ls = line.split()

            # check data
            if i == 0:
                nlines = int(ls[0])
                assert nlines == len(atinfos)
                newlines.append(str(nlines))
                continue

            else:
                idx = int(ls[0]) - 1
                atname, attype = atinfos[idx]

                # Replace atom name
                newline = line[:7] + "%-3s" % atname + line[10:]

                # Replace atom type
                newline = newline[:49] + "%4s" % attype + newline[53:]

                # Reorder connectivity for better comparison with past
                # Solve OpenBabel assigning connectivity to ions
                if atname in [ "Cl-", "Na+", "K+" ]:
                    newline = newline[:53]
                else:
                    conn = sorted(newline[53:].split())
                    conn = [ x for x in conn if x not in ions ]
                    connstr = "%6s" * len(conn)
                    connstr = connstr % tuple(conn)
                    newline = newline[:53] + connstr

                newlines.append(newline)

    # Write the output
    if not outxyz:
        outxyz = txyzfile[:-4] + "_processed.xyz"

    with open(outxyz, 'w') as f:
        for line in newlines:
            f.write(line + "\n")

    return


