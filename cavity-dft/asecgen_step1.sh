#!/bin/bash

Project=`grep "Project" Infos.dat | awk '{ print $2 }'`
sourcedir=`grep "sourcedir" Infos.dat | awk '{ print $2 }'`
chromo=`grep "chromo" Infos.dat | awk '{ print $2 }'`
module add gromacs/2019.4/gcc
export OMPI_MCA_btl_openib_allow_ib=1
export OMPI_MCA_btl_openib_if_include="mlx5_0:1"

__conda_setup="$('/home/ibsbnicigt/nikolaev_d/miniconda3/bin/conda' 'shell.bash' 'hook' 2> /dev/null)"
if [ $? -eq 0 ]; then
    eval "$__conda_setup"
else
    if [ -f "/home/ibsbnicigt/nikolaev_d/miniconda3/etc/profile.d/conda.sh" ]; then
        . "/home/ibsbnicigt/nikolaev_d/miniconda3/etc/profile.d/conda.sh"
    else
        export PATH="/home/ibsbnicigt/nikolaev_d/miniconda3/bin:$PATH"
    fi
fi

alias python=~/miniconda3/bin/python3


## 1. Generating files with correspondence between Gro and Tinker xyz

mkdir correspondence 
cd correspondence
cp ../Dynamic/${Project}.gro .

# Convert gro -> pdb -> Tinker xyz 
gmx editconf -f ${Project}.gro -o ${Project}.pdb -label A
/home/ibsbnicigt/nikolaev_d/miniconda3/bin/python3 $sourcedir/arm_pdb_format.py ${Project}.pdb $chromo
/home/ibsbnicigt/nikolaev_d/miniconda3/bin/python3 $sourcedir/arm_tinker_pdb2xyz.py final_${Project}.pdb

# The fortran script will create the correspondence file between .gro and .xyz.
# Because we use home-built pdb2xyz, there is a one-to-one correspndence
# BUT, I do not know fortran, so for me all fortran parts are absolute black-boxes, I only know what these scripts wants,
# and what it will give me. So we use what we have.

numatoms=`head -1 final_${Project}.xyz`
sed "s/numero/${numatoms}/g" $sourcedir/Templates_gro_tk.f > Template_gro.f
cp $sourcedir/residuetypes.dat .
cp ${Project}.gro final_Config.gro
cp final_${Project}.xyz coordinates_tk.xyz
gfortran Template_gro.f -o Template_gro.x
./Template_gro.x 
rm final_Config.gro coordinates_tk.xyz

# Now we derive the number of protein atoms for other fortran scripts. 

grep "ATOM" ${Project}.pdb > at
sed -i "/SOL/d" at
protatoms=`wc -l at | awk '{print $1}'`
rm at
cd ../




# 2. Generating files with ASEC environment
# We take the last 5000 ps and extract 100 snapshots. So 1 snapshot every 50 ps

numberofsteps=`grep "nsteps" Dynamic/mdrun.mdp | awk '{print $3}'`
pswehave=$(echo "$numberofsteps/1000" | bc)
psweuse=5000
startingstep=$(($pswehave - $psweuse))

mkdir MD_ASEC
cd MD_ASEC

# Extract snapshots from last 5000 ps, every 50 ps 

gmx trjconv -s ../Dynamic/$Project.tpr -f ../Dynamic/$Project.xtc -b $startingstep -skip 50 -o Selected_100.gro << EOF
0
EOF


# This FORTRAN guy will generate the ASEC environment. Don't lose this script, nobody will every create it again.

sed "s/numero/${numatoms}/g; s/protatoms/${protatoms}/g; s/confs/100/g" $sourcedir/MD_ASEC.f > MD_ASEC.f
cp ../correspondence/template* .
gfortran MD_ASEC.f -o MD_ASEC.x
./MD_ASEC.x 
cd ../


# 3. Generating xyz file for optimization 

mkdir conversion
cd conversion

# Best_Config.gro is one of the files generated by MD_ASEC.f. 
# It is the one of 100 configurations that is CLOSEST to the averaged. By averaged I mean the geometry obtained by literally finding the averaged coordinates over the 100 snaphots. 
# We use Best_Config.gro later as the opsin geometry for the next iteration.

cp ../MD_ASEC/Best_Config.gro .
gmx editconf -f Best_Config.gro -o ${Project}.pdb -label A
/home/ibsbnicigt/nikolaev_d/miniconda3/bin/python3 $sourcedir/arm_pdb_format.py ${Project}.pdb $chromo
/home/ibsbnicigt/nikolaev_d/miniconda3/bin/python3 $sourcedir/arm_tinker_pdb2xyz.py final_${Project}.pdb

# Now we want to insert the link atom to finally run the Molcas/Tinker calculation 

cp ../../files/final_${Project}.key .
cp ../../files/melacu63.prm .
/home/ibsbnicigt/nikolaev_d/7.8.dev/tinker/bin_qmmm/xyzedit final_${Project}.xyz << EOF
20
1
EOF

cd ../

# 4.  Generating parameters for ASEC pseudoatoms, ASEC-files for Molcas-Tinker. Again, this is magic for me. But it works correctly.
#     We start with Hartree-Fock here.
#     Here we use the melacu63.prm file. You can have another one. But either you re-write a code to read the name of param file, or you rename the file, as I do.

mkdir calculations
cd calculations
mkdir dft 
cd dft 
cp ../../MD_ASEC/list_tk.dat .
cp ../../MD_ASEC/ASEC_tk.xyz .
cp $sourcedir/ASEC.f .
cp ../../../files/melacu63.prm .
cp $sourcedir/New_parameters.f .
cp ../../conversion/final_${Project}.xyz_2 ${Project}_dft_old.xyz 
cp ../../conversion/final_${Project}.xyz_2 coordinates_tk.xyz 
sed -i "s/numero/${numatoms}/g" ASEC.f 
gfortran ASEC.f -o ASEC.x
./ASEC.x 
mv new_coordinates_tk.xyz ${Project}_dft.xyz 

prm=melacu63

grep "atom     " $prm.prm > atom.dat
numindx2=`grep -c "atom     " atom.dat`
sed -i "s|atomos|$numindx2|g" New_parameters.f

grep "charge   " $prm.prm > charges.dat
numcharges=`grep -c "charge   " charges.dat`
sed -i "s|cargas|$numcharges|g" New_parameters.f
sed -i "s|numero|$numatoms|g" New_parameters.f

grep "vdw      " $prm.prm > vdw.dat
numvdw=`grep -c "vdw      " vdw.dat`
sed -i "s|vander|$numvdw|g" New_parameters.f
sed -i "s|chnorm=40|chnorm=100|g" New_parameters.f

gfortran New_parameters.f -o New_parameters.x
./New_parameters.x

atom=`grep -n "atom     " $prm.prm | awk '{print $1}' FS=":" | tail -n1`
head -n$atom $prm.prm > temp1
cat temp1 new_atom.dat > temp2

vdw=`grep -n "vdw      " $prm.prm | awk '{print $1}' FS=":" | tail -n1`
head -n$vdw $prm.prm | tail -n$(($vdw-$atom)) >> temp2
cat temp2 new_vdw.dat > temp3

charge=`grep -n "charge   " $prm.prm | awk '{print $1}' FS=":" | tail -n1`
head -n$charge $prm.prm | tail -n$(($charge-$vdw)) >> temp3
cat temp3 new_charges.dat > temp4

last=`wc -l $prm.prm | awk '{print $1}'`
tail -n$(($last-$charge)) $prm.prm >> temp4

mv $prm.prm old_$prm.prm
mv temp4 $prm.prm
rm temp* vdw.dat atom.dat charges.dat new_atom.dat 

cp ../../../files/${Project}_dft.key .
cp ../../../files/${Project}_dft.input .

sed "s/XXX/${Project}_dft/g" ${sourcedir}/molcas.sh > molcas.sh

# We have the one-processor version. 
bash /home/ibsbnicigt/nikolaev_d/bin/mBASH molcas -Npr 1 -Time 30
cd ../../
